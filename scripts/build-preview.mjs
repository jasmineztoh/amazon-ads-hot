import fs from 'node:fs/promises';
import { stripTypeScriptTypes } from 'node:module';
const { buildContent } = await import('../modules/local-mvp/publish.ts');
const content = await buildContent();
await fs.mkdir('site/preview', { recursive: true });
await fs.writeFile('site/preview/content.json', JSON.stringify(content, null, 2) + '\n');
const js = stripTypeScriptTypes(await fs.readFile('industry/curation.ts', 'utf8')).replace(/[ \t]+$/gm, '');
await fs.writeFile('site/preview/curation.js', '// 由 scripts/build-preview.mjs 生成；请修改 industry/curation.ts。\n' + js);
console.log(JSON.stringify({ articles: content.total, groupedRows: content.groupedRows, sections: content.sections }));
process.exit(0);
